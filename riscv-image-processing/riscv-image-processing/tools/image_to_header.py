#!/usr/bin/env python3
"""Convert any Pillow-supported image into a 320x240 RGB332 C header.

The generated header intentionally keeps the original lab's tiger_raw and
 tiger_raw_len identifiers so the archived src/main.c requires no edits.
"""

import argparse
from pathlib import Path

from PIL import Image, ImageOps

WIDTH = 320
HEIGHT = 240
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "src" / "tiger_image.h"


def convert_to_rgb332(input_path: Path) -> bytes:
    """Center-crop to 4:3, resize, then pack RRR GGG BB into one byte."""
    with Image.open(input_path) as source:
        rgb = ImageOps.exif_transpose(source).convert("RGB")
        resized = ImageOps.fit(
            rgb, (WIDTH, HEIGHT), method=Image.Resampling.LANCZOS
        )
        rgb_bytes = resized.tobytes()
        return bytes(
            ((rgb_bytes[i] >> 5) << 5)
            | ((rgb_bytes[i + 1] >> 5) << 2)
            | (rgb_bytes[i + 2] >> 6)
            for i in range(0, len(rgb_bytes), 3)
        )


def write_header(pixels: bytes, output_path: Path) -> None:
    if len(pixels) != WIDTH * HEIGHT:
        raise ValueError("Expected exactly 320 * 240 bytes")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="ascii", newline="\n") as out:
        out.write(
            "/* Auto-generated by tools/image_to_header.py. */\n"
            "/* Any source picture can be used; RGB332, 320 x 240, row-major. */\n"
            "#ifndef TIGER_IMAGE_H\n#define TIGER_IMAGE_H\n\n"
            "#include <stdint.h>\n\n"
            "static const uint8_t tiger_raw[] = {\n"
        )
        for offset in range(0, len(pixels), 16):
            line = ", ".join(f"0x{value:02X}" for value in pixels[offset : offset + 16])
            out.write(f"    {line},\n")
        out.write(
            "};\n\n"
            "static const unsigned int tiger_raw_len = sizeof(tiger_raw);\n\n"
            "#endif /* TIGER_IMAGE_H */\n"
        )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Convert any photo to the RGB332 C header required by the RISC-V lab."
    )
    parser.add_argument("image", type=Path, help="Input image (PNG, JPG, etc.)")
    parser.add_argument(
        "-o", "--output", type=Path, default=DEFAULT_OUTPUT,
        help="Header output path (default: src/tiger_image.h)",
    )
    args = parser.parse_args()

    try:
        pixels = convert_to_rgb332(args.image)
        write_header(pixels, args.output)
    except (OSError, ValueError) as exc:
        parser.exit(status=1, message=f"Image conversion failed: {exc}\n")

    print(f"Created {args.output} ({WIDTH}x{HEIGHT}, {len(pixels):,} RGB332 bytes)")
    print("The header defines tiger_raw and tiger_raw_len for src/main.c.")


if __name__ == "__main__":
    main()
